// The seed migration for the taxonomy (P4.8, D-090), printed from `tree.ts`:
//
//   npm run taxonomy:sql --workspace @sarvis/pipeline > supabase/migrations/<version>_taxonomy_v<x_y>.sql
//
// It upserts the categories level by level (a child's parent must exist first), then the OFF tag
// and StatCan label mappings as `approved` / `auto` reference data. The rows travel as compact
// JSON so the file stays small. Re-runnable: a second apply changes nothing, because each upsert
// only touches a row whose mirrored columns differ, and an admin's mapping is never overwritten.
import { pathToFileURL } from 'node:url';

import {
  STRONG_CONFIDENCE,
  TAXONOMY,
  TAXONOMY_METHOD_VERSION,
  WEAK_CONFIDENCE,
  type NodeSpec,
  flattenTaxonomy,
} from './tree.ts';

/** The checked-in migration that holds this version's seed (a unit test compares the two). */
export const TAXONOMY_MIGRATION = '20261111223435_taxonomy_v1_1.sql';
/** When the mappings were made: their `fetched_at` and `reviewed_at`. */
export const TAXONOMY_MADE_AT = '2026-11-11T00:00:00Z';
export const TAXONOMY_DOC_URL =
  'https://github.com/LukaMS/sarvis/blob/main/docs/catalog/TAXONOMY.md';

const json = (v: unknown) => `$j$${JSON.stringify(v)}$j$::jsonb`;

function categoriesSql(level: number, tree: readonly NodeSpec[]): string {
  const rows = flattenTaxonomy(tree).filter((r) => r.level === level);
  const data = rows.map((r) => [r.slug, r.name, r.sortOrder, r.soldLoose ? 1 : 0]);
  const parent =
    level === 0
      ? 'null::uuid'
      : `(select p.id from public.categories p where p.slug = regexp_replace(e->>0, '/[^/]+$', ''))`;
  return `-- Level ${level}: ${rows.length} categories, as [slug, name, sort_order, sold_loose].
insert into public.categories as c (slug, name, parent_id, level, sort_order, sold_loose)
select e->>0, e->>1, ${parent}, ${level}, (e->>2)::int, (e->>3) = '1'
from jsonb_array_elements(${json(data)}) as e
on conflict (slug) do update set
  name = excluded.name,
  parent_id = excluded.parent_id,
  sort_order = excluded.sort_order,
  sold_loose = excluded.sold_loose
where (c.name, c.parent_id, c.sort_order, c.sold_loose)
  is distinct from (excluded.name, excluded.parent_id, excluded.sort_order, excluded.sold_loose);
`;
}

/** `{ slug: [key, …] }`, a `~` before a weak key. */
function keysBySlug(
  tree: readonly NodeSpec[],
  pick: (n: NodeSpec) => readonly string[] | undefined,
) {
  const out: Record<string, string[]> = {};
  const walk = (nodes: readonly NodeSpec[], parent: string | null) => {
    for (const n of nodes) {
      const slug = parent ? `${parent}/${n.key}` : n.key;
      const keys = pick(n) ?? [];
      if (keys.length > 0) out[slug] = [...keys];
      if (n.children) walk(n.children, slug);
    }
  };
  walk(tree, null);
  return out;
}

function mappingsSql(
  sourceKey: string,
  what: string,
  data: Record<string, string[]>,
  confidence: string,
): string {
  const count = Object.values(data).reduce((n, keys) => n + keys.length, 0);
  return `-- ${what}: ${count} mappings under the \`${sourceKey}\` source, as { slug: [key, …] }.
insert into public.category_mappings as m (
  source_id, source_category_key, category_id, confidence,
  review_status, reviewed_at, decision_method,
  source_url, fetched_at, method, method_version
)
select s.id, ltrim(k.key, '~'), c.id, ${confidence},
  'approved', timestamptz '${TAXONOMY_MADE_AT}', 'auto',
  '${TAXONOMY_DOC_URL}', timestamptz '${TAXONOMY_MADE_AT}', 'derived', '${TAXONOMY_METHOD_VERSION}'
from jsonb_each(${json(data)}) as g (slug, keys)
cross join lateral jsonb_array_elements_text(g.keys) as k (key)
join public.categories c on c.slug = g.slug
cross join (select id from public.sources where key = '${sourceKey}') s
on conflict (source_id, source_category_key) do update set
  category_id = excluded.category_id,
  confidence = excluded.confidence,
  source_url = excluded.source_url,
  fetched_at = excluded.fetched_at,
  method = excluded.method,
  method_version = excluded.method_version
where m.decision_method is distinct from 'admin'
  and (m.category_id, m.confidence, m.source_url, m.fetched_at, m.method, m.method_version)
  is distinct from (excluded.category_id, excluded.confidence, excluded.source_url,
                    excluded.fetched_at, excluded.method, excluded.method_version);
`;
}

export function taxonomySql(tree: readonly NodeSpec[] = TAXONOMY): string {
  const rows = flattenTaxonomy(tree);
  const weak = WEAK_CONFIDENCE.toFixed(2);
  const strong = STRONG_CONFIDENCE.toFixed(2);
  return [
    `-- P4.8: the Sarvis taxonomy ${TAXONOMY_METHOD_VERSION} (docs/catalog/TAXONOMY.md, D-090).
-- Generated by \`npm run taxonomy:sql --workspace @sarvis/pipeline\` from pipeline/src/taxonomy/tree.ts;
-- edit the tree, not this file. ${rows.length} categories (${rows.filter((r) => r.isLeaf).length} leaves).
-- Mappings are reference data: approved automatically, and an admin decision is never overwritten.
`,
    categoriesSql(0, tree),
    categoriesSql(1, tree),
    categoriesSql(2, tree),
    mappingsSql(
      'off',
      'OFF categories_tags',
      keysBySlug(tree, (n) => n.off),
      `case when k.key like '~%' then ${weak} else ${strong} end`,
    ),
    mappingsSql(
      'statcan-18100245',
      'StatCan product labels',
      keysBySlug(tree, (n) => n.statcan),
      '1.00',
    ),
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  process.stdout.write(taxonomySql());
}
